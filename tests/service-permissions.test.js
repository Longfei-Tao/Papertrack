const { test, beforeEach } = require('node:test')
const assert = require('node:assert/strict')
let db
global.wx = { getStorageSync: () => db, setStorageSync: (_, value) => { db = structuredClone(value) } }
const storage = require('../services/storage')
const papers = require('../services/paperService')
const teams = require('../services/teamService')
beforeEach(() => { db = require('../services/seed').build() })
test('viewer cannot mutate papers or manage team', () => {
  storage.setMeta('currentTeamId', 'team_002')
  const before = JSON.stringify(db)
  assert.throws(() => papers.createPaper({ title: 'Forbidden' }), /权限/)
  assert.throws(() => papers.updatePaper('paper_101', { title: 'Forbidden' }), /权限/)
  assert.throws(() => papers.softDeletePaper('paper_101'), /权限/)
  assert.throws(() => teams.updateMemberRole('team_002', 'user_001', 'admin'), /权限/)
  assert.throws(() => teams.removeMember('team_002', 'user_006'), /权限/)
  assert.throws(() => teams.refreshInviteCode('team_002'), /权限/)
  assert.equal(JSON.stringify(db), before)
})
test('admin can create, update and soft delete a paper', () => {
  const paper = papers.createPaper({ title: 'Audit', ownerIds: ['user_001'] })
  assert.equal(papers.updatePaper(paper.id, { ...paper, title: 'Updated' }).changed, true)
  assert.equal(papers.softDeletePaper(paper.id), true)
})
test('member cannot grant themselves admin or set an invalid role', () => {
  storage.setMeta('currentUserId', 'user_002')
  assert.throws(() => teams.updateMemberRole('team_001', 'user_002', 'admin'), /权限/)
  storage.setMeta('currentUserId', 'user_001')
  assert.throws(() => teams.updateMemberRole('team_001', 'user_002', 'invalid'), /角色/)
})
test('queries ignore forged role and user and deny foreign paper history', () => {
  storage.setMeta('currentUserId', 'outsider')
  assert.deepEqual(papers.queryPapers({ teamId: 'team_001', role: 'admin', userId: 'user_001', scope: 'all' }), [])
  assert.equal(papers.getRawPaper('paper_101'), null)
  assert.deepEqual(papers.getStatusHistory('paper_101'), [])
})
test('member can edit own paper and cannot edit another member paper', () => {
  storage.setMeta('currentUserId', 'user_002')
  const paper = papers.createPaper({ title: 'Own', ownerIds: ['user_002'] })
  assert.equal(papers.updatePaper(paper.id, { ...paper, title: 'Own updated' }).changed, true)
  const other = papers.createPaper({ title: 'Other', ownerIds: ['user_003'] })
  const before = JSON.stringify(db)
  assert.throws(() => papers.updatePaper(other.id, { ...other, title: 'Forbidden' }), /权限/)
  assert.throws(() => papers.softDeletePaper(other.id), /权限/)
  assert.equal(JSON.stringify(db), before)
  assert.equal(papers.softDeletePaper(paper.id), true)
})
test('admin cannot use current team context to edit a foreign team', () => {
  const before = JSON.stringify(db)
  assert.throws(() => papers.createPaper({ teamId: 'team_002', title: 'Foreign' }), /权限/)
  assert.throws(() => papers.softDeletePaper('paper_101'), /权限/)
  assert.equal(JSON.stringify(db), before)
})
